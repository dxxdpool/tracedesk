"""Markdown report of one investigation, built only from the ledger.

Pure functions: the route loads the rows, `render_report` turns them into text. Two rules matter:
- "Root cause" lists only `verified` hypotheses. Without one it says "No root cause verified", and
  every other hypothesis appears under "Remaining uncertainty", labelled as a hypothesis.
- Everything that came from agents or the repo (problem, hypothesis text, notes, snippets, commands,
  reasons) is untrusted, so it is escaped or fenced and can never add links, HTML or headings.
"""

import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass

from app.models import (
    Evidence,
    EvidenceKind,
    EvidenceSource,
    Experiment,
    ExperimentOutcome,
    ExperimentStatus,
    Hypothesis,
    HypothesisEvent,
    HypothesisStatus,
    Investigation,
)

NO_ROOT_CAUSE = "No root cause verified."
SHORT_ID = 8
MAX_INLINE_CHARS = 300
# Characters that could start Markdown formatting, links or HTML inside a line of untrusted text.
MARKDOWN_SPECIAL = re.compile(r"([\\`*_\[\]|~#])")


@dataclass(frozen=True)
class ReportData:
    investigation: Investigation
    hypotheses: Sequence[Hypothesis]
    events: Sequence[HypothesisEvent]
    evidence: Sequence[Evidence]
    experiments: Sequence[Experiment]


# --- escaping -----------------------------------------------------------------------------------


def text(value: str | None, limit: int = MAX_INLINE_CHARS) -> str:
    """One line of untrusted text, safe inside a paragraph, list item or table cell."""
    flat = " ".join((value or "").split())
    if len(flat) > limit:
        flat = flat[:limit] + "…"
    flat = flat.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return MARKDOWN_SPECIAL.sub(r"\\\1", flat)


def code(value: str) -> str:
    """Inline code that cannot be closed early by backticks in the value."""
    flat = " ".join(value.split())
    fence = "`" * (max((len(run) for run in re.findall(r"`+", flat)), default=0) + 1)
    pad = " " if flat.startswith("`") or flat.endswith("`") else ""
    return f"{fence}{pad}{flat}{pad}{fence}"


def code_block(value: str) -> list[str]:
    fence = "`" * max(3, max((len(run) for run in re.findall(r"`+", value)), default=0) + 1)
    return [fence, *value.splitlines(), fence]


def short(row_id: object) -> str:
    return str(row_id)[:SHORT_ID]


def citation(evidence: Evidence) -> str:
    if evidence.line_start is not None and evidence.file_path:
        return code(f"{evidence.file_path}:{evidence.line_start}-{evidence.line_end}")
    if evidence.commit_sha:
        where = f" in {code(evidence.file_path)}" if evidence.file_path else ""
        return f"commit {code(evidence.commit_sha[:12])}{where}"
    if evidence.experiment_id:
        return f"experiment {code(short(evidence.experiment_id))}"
    return text(evidence.source_type.value)


# --- sections -----------------------------------------------------------------------------------


def render_report(data: ReportData) -> str:
    inv = data.investigation
    lines = [
        f"# Investigation {short(inv.id)}",
        "",
        "Generated by TraceDesk from the Evidence Ledger. Only hypotheses the server accepted as `verified` "
        "(a completed, human-approved experiment confirmed them) are stated as findings.",
        "",
        "## Problem",
        "",
        text(inv.problem, limit=2000),
        "",
        "## Repository",
        "",
        f"- Source: {code(inv.repo_url)}",
        f"- Pinned commit: {code(inv.repo_sha or 'not pinned')}",
        f"- Investigation: {code(str(inv.id))}, status {code(inv.status.value)}",
        "",
    ]
    for section in (_root_cause, _relevant_files, _hypotheses, _experiments, _uncertainty, _next_steps):
        lines += section(data)
    return "\n".join(lines).rstrip() + "\n"


def _evidence_for(data: ReportData, hypothesis: Hypothesis, kind: EvidenceKind) -> list[Evidence]:
    return [e for e in data.evidence if e.hypothesis_id == hypothesis.id and e.kind == kind]


def _confirming(data: ReportData, hypothesis: Hypothesis) -> list[Experiment]:
    return [
        x
        for x in data.experiments
        if x.hypothesis_id == hypothesis.id
        and x.status == ExperimentStatus.COMPLETED
        and x.outcome == ExperimentOutcome.CONFIRMS
    ]


def _verified(data: ReportData) -> list[Hypothesis]:
    return [h for h in data.hypotheses if h.status == HypothesisStatus.VERIFIED]


def _evidence_items(rows: Iterable[Evidence]) -> list[str]:
    return [f"- {citation(e)}: {text(e.note) or '(no note)'} (by {text(e.created_by)})" for e in rows]


def _root_cause(data: ReportData) -> list[str]:
    lines = ["## Root cause", ""]
    verified = _verified(data)
    if not verified:
        return [*lines, NO_ROOT_CAUSE, ""]
    for hypothesis in verified:
        lines += [f"**{text(hypothesis.text, limit=1000)}**", ""]
        lines += [f"Verified ({code(short(hypothesis.id))}) by:", ""]
        lines += [
            f"- experiment {code(short(x.id))}: {code(x.command)} approved by {text(x.approved_by)}, "
            f"exit code {x.exit_code}, outcome {code(x.outcome.value if x.outcome else '-')}"
            for x in _confirming(data, hypothesis)
        ]
        lines += [
            "",
            "Supporting evidence:",
            "",
            *_evidence_items(_evidence_for(data, hypothesis, EvidenceKind.SUPPORTING)),
        ]
        lines.append("")
    return lines


def _relevant_files(data: ReportData) -> list[str]:
    cited = [e for e in data.evidence if e.source_type == EvidenceSource.CODE_REF and e.snippet is not None]
    if not cited:
        return []
    lines = [
        "## Relevant code",
        "",
        "Each snippet was read by the server at the pinned commit, not written by an agent.",
        "",
    ]
    seen: set[tuple[str | None, int | None, int | None]] = set()
    for evidence in cited:
        key = (evidence.file_path, evidence.line_start, evidence.line_end)
        if key in seen:
            continue
        seen.add(key)
        lines += [f"{citation(evidence)}", "", *code_block(evidence.snippet or ""), ""]
    return lines


def _hypotheses(data: ReportData) -> list[str]:
    lines = ["## Hypotheses", ""]
    for hypothesis in data.hypotheses:
        label = "Root cause" if hypothesis.status == HypothesisStatus.VERIFIED else "Hypothesis"
        lines += [
            f"### {label} {short(hypothesis.id)}: {hypothesis.status.value}",
            "",
            f"{text(hypothesis.text, limit=1000)} (proposed by {text(hypothesis.created_by)})",
            "",
        ]
        for kind in (EvidenceKind.SUPPORTING, EvidenceKind.CONTRADICTING, EvidenceKind.OBSERVATION):
            rows = _evidence_for(data, hypothesis, kind)
            if rows:
                lines += [f"{kind.value.capitalize()} evidence:", "", *_evidence_items(rows), ""]
        events = [e for e in data.events if e.hypothesis_id == hypothesis.id]
        if events:
            lines += ["| When (UTC) | From | To | By | Reason |", "|---|---|---|---|---|"]
            lines += [
                f"| {e.created_at:%Y-%m-%d %H:%M} | {e.from_status.value} | {e.to_status.value} | "
                f"{text(e.actor)} | {text(e.reason)} |"
                for e in events
            ]
            lines.append("")
    return lines


def _experiments(data: ReportData) -> list[str]:
    if not data.experiments:
        return []
    lines = [
        "## Experiments",
        "",
        "| Id | Hypothesis | Command | Requested by | Approved by | Status | Exit | Duration | Outcome | Log |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for x in data.experiments:
        duration = f"{x.duration_ms} ms" if x.duration_ms is not None else "-"
        exit_code = "-" if x.exit_code is None else str(x.exit_code)
        log = code(x.stdout_path) if x.stdout_path else "-"
        lines.append(
            f"| {short(x.id)} | {short(x.hypothesis_id)} | {code(x.command)} | {text(x.requested_by)} | "
            f"{text(x.approved_by) or '-'} | {x.status.value} | {exit_code} | {duration} | "
            f"{x.outcome.value if x.outcome else '-'} | {log} |"
        )
    return [*lines, ""]


RULED_OUT = frozenset({HypothesisStatus.CONTRADICTED, HypothesisStatus.REJECTED})


def _is_test_file(path: str | None) -> bool:
    """Tests show the bug; they are not where it is fixed."""
    parts = (path or "").replace("\\", "/").split("/")
    return any(part.startswith("test") for part in parts)


def _uncertainty(data: ReportData) -> list[str]:
    open_ones = [h for h in data.hypotheses if h.status != HypothesisStatus.VERIFIED]
    lines = ["## Remaining uncertainty", ""]
    if not open_ones:
        return [*lines, "Every hypothesis in this investigation was verified.", ""]
    lines += ["These are hypotheses, not findings: no approved experiment verified them.", ""]
    for hypothesis in open_ones:
        ruled_out = hypothesis.status in RULED_OUT
        state = "ruled out by contradicting evidence" if ruled_out else "still open"
        lines.append(
            f"- Hypothesis {short(hypothesis.id)} ({hypothesis.status.value}, {state}): {text(hypothesis.text)}"
        )
    return [*lines, ""]


def _next_steps(data: ReportData) -> list[str]:
    lines = ["## Recommended next steps", ""]
    verified = _verified(data)
    if verified:
        for hypothesis in verified:
            places = [
                citation(e)
                for e in _evidence_for(data, hypothesis, EvidenceKind.SUPPORTING)
                if e.line_start and not _is_test_file(e.file_path)
            ]
            where = ", ".join(dict.fromkeys(places)) or "the cited code"
            lines.append(f"- Fix the verified cause in {where}. TraceDesk does not change code itself.")
            lines.append("- Keep the failing test as the regression test for the fix.")
            lines += [
                f"- After the fix, re-run {code(x.command)}: it should pass." for x in _confirming(data, hypothesis)
            ]
        return [*lines, ""]
    supported = [h for h in data.hypotheses if h.status == HypothesisStatus.SUPPORTED]
    if supported:
        lines += [f"- Test supported hypothesis {short(h.id)} with an approved experiment." for h in supported]
    else:
        lines.append("- Gather evidence until a hypothesis is supported, then test it with an approved experiment.")
    return [*lines, ""]
